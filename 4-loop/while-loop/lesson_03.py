total_price = 0
items_count = 0

print("=== Welcome to Supermarket System ===")
print("ملاحظة: اكتب اسم المنتج لإضافته، أو اكتب 'exit' للإنهاء وحساب الفاتورة.\n")

# 1. حلقة استقبال المنتجات
while True:
    product_name = input("Enter Product Name (or 'exit' to finish): ")
    
    # شرط التوقف
    if product_name.lower() == "exit":
        break
    
    # استقبال السعر وتحويله لـ float
    product_price = float(input(f"Enter price for '{product_name}': "))
    
    # إضافة السعر للإجمالي وزيادة عدد المنتجات
    total_price += product_price  # تعني: total_price = total_price + product_price
    items_count += 1

# 2. حساب الخصم بعد الخروج من الحلقة (إذا كان الإجمالي 500 أو أكثر)
discount = 0
if total_price >= 500:
    discount = total_price * 0.10  # خصم 10%
    final_price = total_price - discount
else:
    final_price = total_price

# 3. طباعة الفاتورة والتقرير النهائي
print("\n====================================")
print("🧾 --- الفاتورة النهائية ---")
print(f"عدد المنتجات الشاملة: {items_count}")
print(f"الإجمالي قبل الخصم: {total_price:.2f} جنيه")

if discount > 0:
    print(f"🎉 تهانينا! حصلت على خصم 10%: -{discount:.2f} جنيه")
    print(f"المبلغ النهائي المطلوب دفعه: {final_price:.2f} جنيه")
else:
    print("لم تتجاوز 500 جنيه للحصول على خصم 10%.")
    print(f"المبلغ النهائي المطلوب دفعه: {final_price:.2f} جنيه")

print("====================================")