# الخصم المالي بعد انتهاء المشتريات:

# بعد الخروج من حلقة الإدخال، إذا كان إجمالي المبلغ أكبر من أو يساوي 500 جنيه، يحصل الزبون على خصم قدره 10% من الإجمالي.

