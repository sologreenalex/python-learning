# إذا كان العرض يوم "الثلاثاء" أو يمتلك العميل كوبون خصم ("نعم"): خصم إضافي بقيمة 10 جنيهات من السعر النهائي (بشرط ألا تكون التذكرة مجانية بالفعل).

