# 1. استقبال المدخلات
name = input("أدخل اسمك: ")
age = int(input("أدخل عمرك: "))
day = input("أدخل يوم العرض: ")
has_coupon = input("هل لديك كوبون خصم؟ (نعم/لا): ")

price_ticket = 100
category = ""

# 2. حساب السعر الأساسي بناءً على العمر والتقييم
if age < 10:
    price_ticket = 0
    category = "طفل"
elif 10 <= age <= 18:
    price_ticket = 50  # خصم 50%
    category = "طالب"
elif age > 60:
    price_ticket = 70  # خصم 30%
    category = "كبار السن"
else:
    price_ticket = 100  # السعر كامل
    category = "بالغ"

# 3. شرط الخصم الإضافي (يوم الثلاثاء أو الكوبون)
# يطبق الخصم بشرط أن تكون التذكرة ليست مجانية بالفعل
if (day == "الثلاثاء" or has_coupon == "نعم") and price_ticket > 0:
    
    price_ticket = price_ticket - 10

# 4. طباعة التقرير النهائي
print("\n--------------------------------")
print("🎟️ --- تقرير تذكرة السينما ---")
print(f"اسم العميل: {name}")
print(f"الفئة: {category}")
print(f"السعر النهائي المطلوب دفعه: {price_ticket} جنيه")
print("--------------------------------")